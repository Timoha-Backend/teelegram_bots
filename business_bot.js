const { Telegraf, Markup } = require('telegraf');

// 1. ИНИЦИАЛИЗАЦИЯ И НАСТРОЙКА ШЛЮЗОВ
// Токен тестового бота (можешь взять второй токен у BotFather или использовать старый)
const bot = new Telegraf('9017501148:AAHoZov4gss2E1I3k9CSYqT8JzeJgPtcsno'); 

// Твой личный ID из @userinfobot (сюда бот будет пересылать заявки от клиентов)
const ADMIN_ID = 6138080789; 

// 2. ГЛАВНОЕ МЕНЮ (КОМАНДА /START)
bot.start((ctx) => {
    return ctx.reply(
        `Приветствуем вас в нашей компании, ${ctx.from.first_name}!\nЧем мы можем вам помочь? Выберите интересующий раздел ниже:`,
        Markup.keyboard([
            ['📦 Наши услуги', '💰 Прайс-лист'],
            ['📞 Оставить заявку', 'ℹ️ О нас']
        ]).resize() // resize делает кнопки аккуратными на экране телефона
    );
});

// 3. ОБРАБОТЧИКИ ТЕКСТОВЫХ КНОПОК МЕНЮ
bot.hears('📦 Наши услуги', (ctx) => {
    return ctx.reply(
        '🔥 Мы разрабатываем топовых Telegram-ботов на Node.js под ключ!\n\nРазрабатываем системы автоматизации бизнеса, асинхронные шлюзы и скрипты для розыгрышей.'
    );
});

bot.hears('💰 Прайс-лист', (ctx) => {
    return ctx.reply(
        '💵 Наш актуальный прайс-лист:\n\n• Простой бот для конкурсов — от 2 000 руб.\n• Многофункциональный бизнес-бот — от 4 500 руб.\n• Подключение баз данных и VDS сервера — от 1 500 руб.'
    );
});

bot.hears('ℹ️ О нас', (ctx) => {
    return ctx.reply(
        '🚀 Команда Prime бэкенд-разработки.\n\nПишем чистый асинхронный код без сбоев и лагов. Опыт реальных коммерческих проектов. Конвейер запущен!'
    );
});

// 4. ШЛЮЗ СБОРА ЗАЯВОК (ИНТЕРАКТИВНЫЙ РЕЖИМ)
bot.hears('📞 Оставить заявку', (ctx) => {
    return ctx.reply(
        '✍️ Пожалуйста, напишите в одном сообщении вашу задачу и контактные данные (телефон или юзернейм).\n\nЯ мгновенно передам эту информацию нашему менеджеру!'
    );
});

// Перехватчик любого текстового сообщения от пользователя
bot.on('text', async (ctx) => {
    // Если пользователь просто пишет текст, находясь в меню, не ломаем логику
    const userText = ctx.message.text;
    
    // Защита: игнорируем системные команды
    if (userText.startsWith('/')) return;

    try {
        // 1. Уведомляем клиента, что заявка улетела
        await ctx.reply('✅ Ваша заявка успешно отправлена менеджеру! Мы свяжемся с вами в ближайшее время.');

        // 2. Асинхронно пересылаем всю информацию админу (заказчику) в ЛС
        await ctx.telegram.sendMessage(
            ADMIN_ID,
            `🚨 ПОСТУПИЛА НОВАЯ ЗАЯВКА ОТ КЛИЕНТА!\n\n` +
            `👤 Имя: ${ctx.from.first_name} ${ctx.from.last_name || ''}\n` +
            `🆔 Telegram ID: \`${ctx.from.id}\`\n` +
            `🔗 Профиль: ${ctx.from.username ? '@' + ctx.from.username : 'Скрыт'}\n\n` +
            `📝 Текст заявки:\n"${userText}"`
        );
    } catch (error) {
        console.error('[БЭКЕНД-ОШИБКА ЗАЯВКИ]', error);
    }
});

// 5. ЗАПУСК ДВИЖКА
bot.launch();
console.log('[SERVER] Коммерческий бизнес-бот успешно запущен на Node.js!');
